import { expect, test } from '@playwright/test'

test('la première connexion impose un mot de passe personnel puis ferme la session', async ({ page, baseURL }) => {
  const district = baseURL!.endsWith('3101')
  await page.goto('/login')
  await page.getByLabel('Matricule ou numéro de téléphone').fill(district ? 'ADMIN-TEMP' : 'SCOUT-TEMP')
  await page.getByLabel('Mot de passe', { exact: true }).fill('Secret-Temporaire!42')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page).toHaveURL(/changer-mot-de-passe$/)
  await page.getByLabel('Mot de passe actuel ou temporaire').fill('Secret-Temporaire!42')
  await page.getByLabel('Nouveau mot de passe personnel', { exact: true }).fill('Personnel-Inedit!42')
  await page.getByLabel('Confirmer le nouveau mot de passe').fill('Personnel-Inedit!42')
  const requete = page.waitForRequest((r) => r.url().endsWith('/api/auth/changer-mot-de-passe') && r.method() === 'POST')
  await page.getByRole('button', { name: 'Enregistrer et me reconnecter' }).click()
  expect((await requete).postDataJSON()).toEqual({ motDePasseActuel: 'Secret-Temporaire!42', nouveauMotDePasse: 'Personnel-Inedit!42' })
  await expect(page.getByRole('status')).toContainText('mot de passe personnel est enregistré')
  await page.getByRole('link', { name: 'Se reconnecter', exact: true }).click()
  await expect(page).toHaveURL(/login$/)
})

test('un identifiant refusé conserve la page de connexion', async ({ page }) => {
  await page.goto('/login')
  await page.getByLabel('Matricule ou numéro de téléphone').fill('INVALIDE')
  await page.getByLabel('Mot de passe', { exact: true }).fill('incorrect')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page.getByText('Identifiant ou mot de passe incorrect.', { exact: true })).toBeVisible()
  await expect(page).toHaveURL(/login$/)
})

test('la création génère un secret temporaire sans demander de mot de passe permanent', async ({ page, context, baseURL }) => {
  const district = baseURL!.endsWith('3101')
  await context.addCookies([{ name: 'scout_acces', value: district ? 'admin' : 'paroisse', url: baseURL! }])
  await page.goto(`/${district ? 'admin' : 'dashboard'}/utilisateurs/nouveau`)
  if (district) await page.getByLabel('Paroisse', { exact: false }).selectOption('paroisse-test')
  await page.getByLabel('Nom', { exact: false }).first().fill('Exemple')
  await page.getByLabel('Prénom', { exact: false }).fill('Awa')
  await page.getByLabel('Rôle', { exact: false }).selectOption('CHEF_GROUPE')
  await page.getByLabel('Matricule', { exact: false }).fill('TEST001')
  await expect(page.locator('input[type=password]')).toHaveCount(0)
  const requete = page.waitForRequest((r) => /\/api\/(admin\/)?utilisateurs$/.test(r.url()) && r.method() === 'POST')
  await page.getByRole('button', { name: /Créer (le membre|l.utilisateur)/ }).click()
  expect((await requete).postDataJSON()).not.toHaveProperty('password')
  await expect(page.getByRole('heading', { name: 'Compte créé' })).toBeVisible()
  await expect(page.getByLabel('Mot de passe temporaire', { exact: true })).toHaveValue('Secret-Test-Unique!42')
  await expect(page.getByText(/Remettez ce mot de passe temporaire en personne/)).toBeVisible()
})

test('la désactivation exige confirmation et Échap restaure le focus', async ({ page, context, baseURL }) => {
  const district = baseURL!.endsWith('3101')
  await context.addCookies([{ name: 'scout_acces', value: district ? 'admin' : 'paroisse', url: baseURL! }])
  await page.goto(`/${district ? 'admin' : 'dashboard'}/utilisateurs/membre-test/modifier`)
  await page.getByRole('checkbox').first().uncheck()
  const enregistrer = page.getByRole('button', { name: /Enregistrer les modifications/ })
  await enregistrer.click()
  const dialogue = page.getByRole('alertdialog')
  await expect(dialogue).toBeVisible()
  await expect(dialogue.getByRole('button', { name: 'Annuler' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialogue.getByRole('button', { name: 'Confirmer' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialogue).not.toBeVisible()
  await expect(enregistrer).toBeFocused()
})
